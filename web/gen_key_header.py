#!/usr/bin/env python3
"""Write relay_key.h for port/sign.c from the GHOST_KEY make variable.

The key (hex, the same as relay.key next to server/relay.py) is stored
XOR-masked so it is not a plain string in the WebAssembly.  Without a key
the header is empty and run ends are not signed.  The file is only
rewritten when its contents change, so make does not rebuild needlessly.

usage: gen_key_header.py OUT [HEXKEY]
"""
import hashlib
import sys

out = sys.argv[1]
key_hex = sys.argv[2].strip() if len(sys.argv) > 2 else ""
text = "/* generated by web/gen_key_header.py: no GHOST_KEY, run ends are not signed */\n"
if key_hex:
    key = bytes.fromhex(key_hex)
    mask = hashlib.sha256(key).digest()[0]
    masked = [k ^ ((mask + i * 31) & 0xFF) for i, k in enumerate(key)]
    text = ("/* generated by web/gen_key_header.py from GHOST_KEY (do not commit) */\n"
            "static const unsigned char RELAY_KEY_MASKED[] = { %s };\n"
            "#define RELAY_KEY_MASK 0x%02x\n#define RELAY_KEY_LEN %d\n"
            % (", ".join(str(b) for b in masked), mask, len(key)))
try:
    with open(out) as f:
        if f.read() == text:
            sys.exit(0)
except OSError:
    pass
with open(out, "w") as f:
    f.write(text)
